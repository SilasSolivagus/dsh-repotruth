// 索引的增量契约：第二遍跑同一个 HEAD 必须解析 0 个内容块。
//
// 为什么这条比「索引对不对」更重要：一旦增量失效，每次同步都要把整个仓重读一遍，
// 大仓会从「几秒」变成「几分钟」，而界面上看不出任何区别——只有夜间任务被拖死时才被发现。
// 所以它必须是一条会变红的断言，不是一句注释。
import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { test } from 'node:test'

import { buildIndex, isTestPath, skipDirOf } from '../lib/indexer.js'
import { mirrorClone } from '../lib/git.js'
import { scanRepo } from '../lib/scan.js'

/** 造一个合成仓：页面、组件、第三方目录、测试、自动生成文件、素材、认不得的扩展名全都有。 */
async function makeRepo() {
  const base = await mkdtemp(join(tmpdir(), 'repo-truth-idx-'))
  const dir = join(base, 'fixture-shop')
  await mkdir(dir, { recursive: true })
  const write = async (rel, body) => {
    const full = join(dir, rel)
    await mkdir(dirname(full), { recursive: true })
    await writeFile(full, body, 'utf8')
  }
  await write('package.json', JSON.stringify({ name: 'fixture-shop' }, null, 2))
  await write('src/views/login/index.vue', '<template><LoginForm /></template>\n<script>\nexport default { name: "Login" }\n</script>\n')
  await write('src/views/order/list.vue', '<template><OrderTable /></template>\n')
  await write('src/components/LoginForm.vue', '<template><form /></template>\n')
  await write('src/components/OrderTable.vue', '<template><table /></template>\n')
  await write('src/utils/money.ts', 'export function formatMoney(cents: number) { return cents / 100 }\n')
  await write('src/api/order.ts', "import { formatMoney } from '../utils/money'\nexport async function fetchOrders() { return formatMoney(1) }\n")
  await write('src/views/login/index.test.ts', "import { test } from 'vitest'\ntest('x', () => {})\n")
  await write('vendor/some-lib/index.js', 'export function vendored() {}\n')
  await write('third_party/other/index.js', 'export function other() {}\n')
  await write('testdata/orders.json', '{}\n')
  await write('src/generated/types.ts', '// Code generated by fixture-gen. DO NOT EDIT.\nexport interface Row { id: string }\n')
  await write('public/logo.png', 'not-really-a-png')
  await write('src/legacy/Legacy.HTMLISH', 'unknown extension\n')
  await write('README.md', '# fixture\n\n## 订单\n')

  const git = (...args) =>
    execFileSync('git', ['-c', 'user.name=fixture', '-c', 'user.email=fixture@example.com', ...args], {
      cwd: dir,
      stdio: 'ignore',
    })
  git('init', '--quiet', '-b', 'main')
  git('add', '-A')
  git('commit', '--quiet', '-m', 'fixture: 初始提交')
  return { base, dir }
}

/** 起一份 bare 镜像 + 空索引路径：索引器只认 mirror，不认工作区。 */
async function makeMirror(dir) {
  const base = await mkdtemp(join(tmpdir(), 'repo-truth-idx-mirror-'))
  const mirror = join(base, 'mirror.git')
  const cloned = await mirrorClone(`file://${dir}`, mirror)
  assert.equal(cloned.ok, true, cloned.error)
  return { base, mirror, indexPath: join(base, 'index', 'fixture-shop.json') }
}

test('第二遍跑同一个 HEAD：解析 0 个内容块', async (t) => {
  const repo = await makeRepo()
  const { base, mirror, indexPath } = await makeMirror(repo.dir)
  t.after(async () => {
    await rm(repo.base, { recursive: true, force: true })
    await rm(base, { recursive: true, force: true })
  })

  const first = await buildIndex({ repo: 'fixture-shop', url: 'file:///x', mirrorDir: mirror, indexPath })
  assert.equal(first.ok, true, first.error)
  assert.ok(first.parsedBlobs > 0, '第一次必须真的解析了内容')

  const second = await buildIndex({ repo: 'fixture-shop', url: 'file:///x', mirrorDir: mirror, indexPath })
  assert.equal(second.ok, true, second.error)
  assert.equal(second.parsedBlobs, 0, '同一个 HEAD 第二遍必须解析 0 个内容块')
  // 复用的口径是「文件」，解析的口径是「内容块」：生成代码那个文件第一遍被解析过一次，
  // 第二遍靠 generated 标记直接认出，所以复用数等于上一轮的 files.indexed。
  assert.equal(second.reusedBlobs, first.counts.indexed, '复用的文件数应当等于上一轮真正入库的文件数')
  assert.equal(second.head, first.head)
})

test('改一个文件再跑：只解析这一个新内容块', async (t) => {
  const repo = await makeRepo()
  const { base, mirror, indexPath } = await makeMirror(repo.dir)
  t.after(async () => {
    await rm(repo.base, { recursive: true, force: true })
    await rm(base, { recursive: true, force: true })
  })
  const before = await buildIndex({ repo: 'fixture-shop', url: 'file:///x', mirrorDir: mirror, indexPath })

  await writeFile(join(repo.dir, 'src/utils/money.ts'), 'export function formatMoney(cents: number) { return (cents / 100).toFixed(2) }\n', 'utf8')
  execFileSync('git', ['-c', 'user.name=f', '-c', 'user.email=f@e.com', 'commit', '-am', 'fix: money'], { cwd: repo.dir, stdio: 'ignore' })

  const fetchResult = await import('../lib/git.js').then((m) => m.mirrorFetch(mirror))
  assert.equal(fetchResult.ok, true, fetchResult.error)

  const after = await buildIndex({ repo: 'fixture-shop', url: 'file:///x', mirrorDir: mirror, indexPath })
  assert.equal(after.ok, true, after.error)
  assert.equal(after.parsedBlobs, 1, '只改了一个文件，就只该解析一个新的内容块')
  assert.notEqual(after.head, before.head, '拉到新提交后 HEAD 必须变')
  assert.match(after.head, /^[0-9a-f]{40}$/)
})

test('跳过项必须分项记账，且各项之和等于文件总数', async (t) => {
  const repo = await makeRepo()
  const { base, mirror, indexPath } = await makeMirror(repo.dir)
  t.after(async () => {
    await rm(repo.base, { recursive: true, force: true })
    await rm(base, { recursive: true, force: true })
  })

  const result = await buildIndex({ repo: 'fixture-shop', url: 'file:///x', mirrorDir: mirror, indexPath })
  const counts = result.counts

  assert.equal(counts.dir, 3, 'vendor / third_party / testdata 各算一个')
  assert.equal(counts.test, 1, 'index.test.ts 要按测试跳过')
  assert.equal(counts.generated, 1, 'DO NOT EDIT 的文件要单列')
  assert.equal(counts.asset, 1, 'logo.png 算素材')
  assert.equal(counts.unsupported, 1, '不认识的后缀要如实计入')
  assert.equal(
    counts.total,
    counts.indexed + counts.generated + counts.test + counts.dir + counts.asset + counts.unsupported + counts.large,
    '分项之和必须等于文件总数（漏一项就等于悄悄丢文件）',
  )
  // 「接进来 ≠ 看得见」：总数里有相当一部分没有进入索引。
  assert.ok(counts.indexed < counts.total)
  assert.equal(result.pages, 2, '两个 src/views 页面')
})

test('自动生成的文件不进索引，但第二遍也不能再读它', async (t) => {
  const repo = await makeRepo()
  const { base, mirror, indexPath } = await makeMirror(repo.dir)
  t.after(async () => {
    await rm(repo.base, { recursive: true, force: true })
    await rm(base, { recursive: true, force: true })
  })
  const first = await buildIndex({ repo: 'fixture-shop', url: 'file:///x', mirrorDir: mirror, indexPath })
  const second = await buildIndex({ repo: 'fixture-shop', url: 'file:///x', mirrorDir: mirror, indexPath })
  assert.equal(first.counts.generated, 1)
  assert.equal(second.counts.generated, 1, '第二轮仍然要认出它是生成代码')
  assert.equal(second.parsedBlobs, 0, '认出来的东西不能每轮重读一遍')

  const document = JSON.parse(await readFile(indexPath, 'utf8'))
  assert.equal(Object.keys(document.files).includes('src/generated/types.ts'), false)
  assert.equal(Object.keys(document.generated).length, 1)
})

test('索引里的页面口径与 scan.js 一致（不是第二套扫描器）', async (t) => {
  const repo = await makeRepo()
  const { base, mirror, indexPath } = await makeMirror(repo.dir)
  t.after(async () => {
    await rm(repo.base, { recursive: true, force: true })
    await rm(base, { recursive: true, force: true })
  })
  const result = await buildIndex({ repo: 'fixture-shop', url: 'file:///x', mirrorDir: mirror, indexPath })
  const facts = await scanRepo(repo.dir, { repoName: 'fixture-shop' })
  assert.deepEqual(result.pageItems, facts.pages.items, '索引与工作区扫描必须给出同一份页面清单')
  assert.equal(result.pagesLabel, facts.pages.label)
})

test('删掉索引可重放：重建后内容与第一次一致', async (t) => {
  const repo = await makeRepo()
  const { base, mirror, indexPath } = await makeMirror(repo.dir)
  t.after(async () => {
    await rm(repo.base, { recursive: true, force: true })
    await rm(base, { recursive: true, force: true })
  })
  const first = await buildIndex({ repo: 'fixture-shop', url: 'file:///x', mirrorDir: mirror, indexPath })
  const before = JSON.parse(await readFile(indexPath, 'utf8'))
  await rm(indexPath, { force: true })
  const again = await buildIndex({ repo: 'fixture-shop', url: 'file:///x', mirrorDir: mirror, indexPath })
  const after = JSON.parse(await readFile(indexPath, 'utf8'))
  assert.equal(again.parsedBlobs, first.parsedBlobs, '索引丢了应当能全量重建')
  assert.deepEqual(Object.keys(after.files).sort(), Object.keys(before.files).sort())
  assert.deepEqual(Object.keys(after.blobs).sort(), Object.keys(before.blobs).sort())
})

test('路径判定：测试与第三方目录按「整段目录名」匹配', () => {
  assert.equal(isTestPath('src/views/login/index.test.ts'), true)
  assert.equal(isTestPath('tests/unit/utils.spec.js'), true)
  assert.equal(isTestPath('pkg/server/server_test.go'), true)
  assert.equal(isTestPath('src/test-utils/helper.ts'), false, 'test-utils 不是测试')
  assert.equal(isTestPath('src/views/login/index.vue'), false)
  assert.equal(skipDirOf('vendor/a/b.js'), 'vendor')
  assert.equal(skipDirOf('src/vendor/a.js'), 'vendor')
  assert.equal(skipDirOf('src/vendors/a.js'), null, 'vendors 不是 vendor')
})
