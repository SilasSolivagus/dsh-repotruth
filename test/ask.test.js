// 「问一句」：检索规则与「不能编」。
//
// 这一组测试守的不是准确率，而是诚实度：
// 1. 查得到 → 给候选，并在正文里说清「这只是名字相似」；
// 2. 查不到 → 必须说「没找到」并列出查过什么，不许拿一个分数最高的文件顶上；
// 3. 没索引  → 必须说「我还没看」，不许说成「没有」；
// 4. 被跳过的文件（第三方/生成/测试）里的词，绝不能出现在结果里；
// 5. 正文禁词命中数必须是 0（机器检查，不靠感觉）。
import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { test } from 'node:test'

import { askQuestion, humanizePage, tokenizeQuestion } from '../lib/ask.js'
import { answerBodyText, answerLimits, answerParagraphs, renderAnswer } from '../lib/answer.js'
import { mirrorClone } from '../lib/git.js'
import { buildIndex } from '../lib/indexer.js'
import { productBodyViolations } from '../lib/render.js'

async function makeRepo() {
  const base = await mkdtemp(join(tmpdir(), 'repo-truth-ask-'))
  const dir = join(base, 'fixture-shop')
  await mkdir(dir, { recursive: true })
  const write = async (rel, body) => {
    const full = join(dir, rel)
    await mkdir(dirname(full), { recursive: true })
    await writeFile(full, body, 'utf8')
  }
  await write('src/views/login/index.vue', '<template><LoginForm /></template>\n')
  await write('src/views/order/list.vue', '<template><OrderTable /></template>\n')
  await write('src/components/LoginForm.vue', '<template><form /></template>\n')
  await write('src/components/OrderTable.vue', '<template><table /></template>\n')
  await write('src/utils/money.ts', 'export function formatMoney(cents: number) { return cents / 100 }\n')
  await write('src/api/order.ts', "import { formatMoney } from '../utils/money'\nexport async function fetchOrders() { return formatMoney(1) }\n")
  await write('src/utils/dates.ts', 'export function dayOfWeek(day: string) { return day }\n')
  // 只在文档标题里出现一次的词（发票）、只在文件名里含这几个字母的词（filters ← filter）：
  // 两者都不足以构成「名字层面的命中」，用来钉住检索阈值。
  await write('docs/guide.md', '# 指南\n\n## 发票与结算\n\n流程说明。\n')
  await write('src/utils/filters.ts', 'export function buildFilter() { return {} }\n')
  // 这些词只出现在被跳过的文件里：一旦检索能命中它们，说明跳过规则被绕过了。
  await write('vendor/payment-gateway.js', 'export function settleInvoice() { return "蓝鲸结算" }\n')
  await write('src/generated/types.ts', '// Code generated by fixture-gen. DO NOT EDIT.\nexport interface 蓝鲸订单 { id: string }\n')
  await write('src/views/login/index.test.ts', "import { test } from 'vitest'\ntest('蓝鲸', () => {})\n")
  const git = (...args) =>
    execFileSync('git', ['-c', 'user.name=f', '-c', 'user.email=f@e.com', ...args], { cwd: dir, stdio: 'ignore' })
  git('init', '--quiet', '-b', 'main')
  git('add', '-A')
  git('commit', '--quiet', '-m', 'init')
  return { base, dir }
}

/** 造一份真索引（走同一个 buildIndex），返回给 askQuestion 用的仓库行。 */
async function indexedRepo(t) {
  const repo = await makeRepo()
  const mirrorBase = await mkdtemp(join(tmpdir(), 'repo-truth-ask-mirror-'))
  const mirror = join(mirrorBase, 'mirror.git')
  const cloned = await mirrorClone(`file://${repo.dir}`, mirror)
  assert.equal(cloned.ok, true, cloned.error)
  const indexPath = join(mirrorBase, 'index', 'fixture-shop.json')
  const built = await buildIndex({ repo: 'fixture-shop', url: 'file:///fixture-shop', mirrorDir: mirror, indexPath })
  assert.equal(built.ok, true, built.error)
  t.after(async () => {
    await rm(repo.base, { recursive: true, force: true, maxRetries: 6, retryDelay: 120 })
    await rm(mirrorBase, { recursive: true, force: true, maxRetries: 6, retryDelay: 120 })
  })
  const previous = process.env.REPO_TRUTH_HOME
  const home = join(mirrorBase, 'home')
  await mkdir(join(home, 'index'), { recursive: true })
  await rm(join(home, 'index'), { recursive: true, force: true })
  // askQuestion 通过 paths.indexPath 找索引：把 home 指到镜像目录这一层。
  process.env.REPO_TRUTH_HOME = mirrorBase
  t.after(async () => {
    if (previous === undefined) delete process.env.REPO_TRUTH_HOME
    else process.env.REPO_TRUTH_HOME = previous
  })
  return {
    row: { name: 'fixture-shop', head: built.head, headDate: built.headDate, indexedAt: built.indexedAt },
    indexPath: join(mirrorBase, 'index', 'fixture-shop.json'),
  }
}

test('中文提问命中页面：正文是产品语言、限界框齐全、署名与 meta 都在', async (t) => {
  const { row } = await indexedRepo(t)
  const answer = await askQuestion({ question: '登录页面是怎么做的？', repos: [row] })
  assert.equal(answer.found, true, '这个名字在仓里确实存在')
  assert.ok(answer.matches.some((item) => item.path === 'src/views/login/index.vue'))
  assert.ok(answer.stats.pageNames.includes('login'))

  const { html, body } = renderAnswer(answer, { config: {}, generatedAt: '2026-01-01' })
  assert.deepEqual(productBodyViolations(html), [], '正文里不许出现路径、后缀、驼峰或实现名词')
  assert.ok(body.join('').includes('login'), '正文要用产品语言点出命中的页面名')
  assert.ok(body.join('').includes('名字相似不等于就是它'), '命中时必须带限定')
  assert.ok(html.includes('没找到 ≠ 不存在'))
  assert.ok(html.includes('<footer>由 repotruth 生成 · '), '材料必须带署名')
  assert.match(html, /<meta name="generator" content="repotruth v[^"]+">/)
  assert.ok(html.includes('研发参考'), '代码坐标只在末尾的研发参考里')
  assert.ok(html.indexOf('<details class="devref">') > html.indexOf('这份材料读到哪'), '研发参考在限界框之后')
})

test('查得到时能回答「波及几处」：引用数与最近改动都来自索引', async (t) => {
  const { row } = await indexedRepo(t)
  const answer = await askQuestion({ question: '金额格式化', repos: [row] })
  assert.equal(answer.found, true)
  const money = answer.matches.find((item) => item.path === 'src/utils/money.ts')
  assert.ok(money, '金额 → money 的对照要能让它被找到')
  assert.equal(money.importedBy, 1, 'src/api/order.ts 引用了它，这个数字必须来自索引')
  assert.ok(answer.stats.importedFiles >= 1)
  assert.ok(typeof answer.stats.lastChange === 'string', '改动时间来自本机历史窗口')
})

test('查不到就说没找到：正文与限界框都写明「查过、没命中」', async (t) => {
  const { row } = await indexedRepo(t)
  const answer = await askQuestion({ question: '发票开具与电子签章', repos: [row] })
  assert.equal(answer.found, false)
  assert.equal(answer.matches.length, 0, '没有命中就是 0 条，不许给「最像的那个」')

  const { html, body } = renderAnswer(answer, { config: {}, generatedAt: '2026-01-01' })
  assert.match(body[0], /没能在已索引的代码里找到/)
  assert.match(body[1], /不是「不存在」/)
  assert.ok(body[1].includes('发票'), '要把检索词写出来，读的人才知道查过什么')
  assert.ok(html.includes('没找到 ≠ 不存在'))

  const limits = answerLimits(answer)
  assert.ok(limits.some((item) => item.title === '读了什么'))
  assert.ok(limits.some((item) => item.title === '读不到'))
  assert.ok(limits.some((item) => item.title === '查过的范围'))
  assert.deepEqual(productBodyViolations(html), [], '没找到的正文同样要干净')
})

test('被跳过的文件里的词不能出现：第三方 / 生成代码 / 测试', async (t) => {
  const { row } = await indexedRepo(t)
  // 「蓝鲸」只出现在 vendor/、生成代码和测试文件里；必须查不到。
  const answer = await askQuestion({ question: '蓝鲸', repos: [row] })
  assert.equal(answer.found, false, '跳过的文件不许漏进检索结果')
  assert.equal(answer.matches.length, 0)
  assert.ok(answer.skipped.generated >= 1)
  assert.ok(answer.skipped.dir >= 1)
  assert.ok(answer.skipped.test >= 1)

  // 同一个仓里查「订单」应当命中正常代码，但绝不能命中被跳过的那三个文件。
  const orders = await askQuestion({ question: '订单列表', repos: [row] })
  assert.equal(orders.found, true)
  for (const item of orders.matches) {
    assert.doesNotMatch(item.path, /^vendor\//)
    assert.doesNotMatch(item.path, /^src\/generated\//)
    assert.doesNotMatch(item.path, /\.test\./)
  }
})

test('还没建过索引：说「我没看」，不说「没有」', async (t) => {
  const empty = await mkdtemp(join(tmpdir(), 'repo-truth-ask-empty-'))
  const previous = process.env.REPO_TRUTH_HOME
  process.env.REPO_TRUTH_HOME = empty
  t.after(async () => {
    if (previous === undefined) delete process.env.REPO_TRUTH_HOME
    else process.env.REPO_TRUTH_HOME = previous
    await rm(empty, { recursive: true, force: true })
  })
  const answer = await askQuestion({ question: '登录页面怎么做', repos: [{ name: 'not-indexed-yet' }] })
  assert.equal(answer.found, false)
  assert.equal(answer.state, 'no-index')
  const paragraphs = answerParagraphs(answer, '2026-01-01')
  assert.match(paragraphs[0], /还没有任何一个仓建过索引/)
  assert.match(paragraphs[1], /不代表你要找的东西不存在/)
  assert.equal(answer.missing.length, 1)
  assert.ok(answerLimits(answer).some((item) => item.text.includes('什么都没读')))
})

test('检索规则：虚词被丢掉，中文说法能落到英文命名上', () => {
  const tokens = tokenizeQuestion('登录页面是怎么做的？')
  assert.ok(tokens.en.includes('login'), '登录 应展开成 login')
  assert.equal(tokens.zh.includes('页面'), false, '虚词留在词表里会把任何文件都算成候选')
  assert.equal(tokens.zh.includes('怎么'), false)
  assert.equal(humanizePage('src/views/login/index'), 'login')
  assert.equal(humanizePage('src/pages/userProfile/index'), 'user profile')
  assert.equal(humanizePage('/'), '首页')
})

test('弱命中不算命中：只在文档标题里出现过、或只是名字里含这几个字母', async (t) => {
  const { row } = await indexedRepo(t)
  // 「发票」只出现在 docs/guide.md 的二级标题里：一次词面命中（权重 1）不足以给结论。
  const invoice = await askQuestion({ question: '发票', repos: [row] })
  assert.equal(invoice.found, false, '只在文档标题里出现过的词不该产出候选')

  // 「筛选」→ filter，只匹配到 utils/filters.ts 这种「名字里含这几个字母」（权重 2），同样不够。
  const filter = await askQuestion({ question: '筛选', repos: [row] })
  assert.equal(filter.found, false, '只命中一段子串不该产出候选')
})

test('一条都命中不了时不会「凑」：通用词不算命中', async (t) => {
  const { row } = await indexedRepo(t)
  // 「index」出现在很多路径里，但它不是需求词；只靠它不该产出候选。
  const answer = await askQuestion({ question: '怎么', repos: [row] })
  assert.equal(answer.found, false)
  assert.deepEqual(answer.terms, [])
})
